"""Write a placeholder timeline (vo.ts) from narration.json without any TTS, so the picture can be blocked out first.

Words get a reading-speed duration (~150 wpm, longer for long words and after punctuation); sections and lines are laid
out with the same lead / chapter-gap / extra knobs as assemble_natural.py. Replace with the real timeline once voiced:
every at() anchor keeps working because anchors are words, not seconds.
Chinese ("lang": "zh") is timed per character at about 4.5 characters per second.
usage: python -X utf8 tools/fake_timeline.py narration.json src/film/data/vo.ts
"""
import json, sys
from pathlib import Path
from textutil import lang_of, tokens, wide

spec = json.loads(Path(sys.argv[1]).read_text(encoding="utf-8"))
TL = spec.get("timeline", {})
LANG = lang_of(spec)
t = TL.get("lead", 7.0)
T = {}
for si, sec in enumerate(s["key"] for s in spec["sections"]):
    ls = [l for l in spec["lines"] if l["id"].startswith(sec)]
    if not ls: continue
    if si > 0: t += TL.get("chapter_gap", {}).get(sec, 1.7)
    for li, l in enumerate(ls):
        if li > 0: t += 0.45 + TL.get("extra", {}).get(l["id"], 0.0)
        words, start = [], t
        for w in tokens(l["text"], LANG):
            d = 0.22 if wide(w[0]) else 0.16 + 0.045 * len(w)
            words.append([w, round(t, 3), round(t + d, 3)])
            t += d + (0.28 if w[-1] in ".,:;?!，。、：；？！" else 0.04)
        T[l["id"]] = {"start": round(start - 0.1, 3), "end": round(t + 0.15, 3), "text": l["text"], "words": words}
total = round(t + TL.get("tail", 2.6), 3)
out = Path(sys.argv[2]); out.parent.mkdir(parents=True, exist_ok=True)
out.write_text(
    "// Generated by tools/fake_timeline.py (placeholder timing, no audio). Replace via tools/assemble_natural.py.\n"
    "export type VoLine = { start: number; end: number; text: string; words: Array<[string, number, number]> };\n"
    f"export const VO_TOTAL = {total};\n"
    f"export const VO: Record<string, VoLine> = {json.dumps(T, ensure_ascii=False, indent=1)};\n", encoding="utf-8")
print(len(T), "lines, total", total, "s")
